-- Atomic field-level JSON merge prevents lost changes from separate requests.
create or replace function public.sj_patch_settings(p_user_id bigint, p_patch jsonb, p_defaults jsonb)
returns jsonb language plpgsql set search_path = public as $$
declare result jsonb;
begin
    insert into sj_users(user_id,chat_id,settings)
        values(p_user_id,p_user_id,p_defaults || p_patch)
        on conflict(user_id) do nothing;
    update sj_users set settings=settings || p_patch,updated_at=now()
        where user_id=p_user_id returning settings into result;
    return result;
end $$;

create or replace function public.sj_acquire_lease(p_key text,p_owner text,p_seconds integer)
returns boolean language plpgsql set search_path = public as $$
declare claimed text;
begin
    if p_seconds < 1 or p_seconds > 1800 or length(p_key)>200 or length(p_owner)>100 then
        raise exception 'Invalid lease parameters';
    end if;
    delete from sj_leases where expires_at < now() and key<>p_key;
    insert into sj_leases(key,owner,expires_at) values(p_key,p_owner,now()+make_interval(secs=>p_seconds))
        on conflict(key) do update set owner=excluded.owner,expires_at=excluded.expires_at
        where sj_leases.expires_at <= now() or sj_leases.owner=excluded.owner
        returning owner into claimed;
    return claimed is not null;
end $$;
create or replace function public.sj_release_lease(p_key text,p_owner text)
returns void language sql set search_path = public as $$
    delete from sj_leases where key=p_key and owner=p_owner;
$$;

-- Atomic, persistent webhook claim; duplicate requests after sleep/redeploy are
-- suppressed. Completed update IDs contain no user/chat IDs and expire in 2 days.
create or replace function public.sj_claim_update(p_update_id bigint,p_owner text,p_seconds integer)
returns text language plpgsql set search_path = public as $$
declare claimed bigint;
begin
    if p_update_id < 0 or p_seconds < 1 or p_seconds > 1800 or length(p_owner)>100 then
        raise exception 'Invalid update claim parameters';
    end if;
    delete from sj_webhook_events where completed and expires_at < now();
    if exists(select 1 from sj_webhook_events where update_id=p_update_id and completed) then
        return 'completed';
    end if;
    insert into sj_webhook_events(update_id,owner,expires_at)
        values(p_update_id,p_owner,now()+make_interval(secs=>p_seconds))
        on conflict(update_id) do update set owner=excluded.owner,expires_at=excluded.expires_at
        where not sj_webhook_events.completed and sj_webhook_events.expires_at <= now()
        returning update_id into claimed;
    return case when claimed is null then 'busy' else 'claimed' end;
end $$;
create or replace function public.sj_finish_update(p_update_id bigint,p_owner text)
returns void language sql set search_path = public as $$
    update sj_webhook_events set completed=true,expires_at=now()+interval '2 days'
        where update_id=p_update_id and owner=p_owner;
$$;
create or replace function public.sj_release_update(p_update_id bigint,p_owner text)
returns void language sql set search_path = public as $$
    delete from sj_webhook_events where update_id=p_update_id and owner=p_owner and not completed;
$$;

create or replace function public.sj_keep_publication_date()
returns trigger language plpgsql set search_path = public as $$
begin
    if old.published_at is not null then
        new.published_at=old.published_at;
        new.publication_date_only=old.publication_date_only;
    end if;
    return new;
end $$;
drop trigger if exists sj_keep_publication on public.sj_jobs;
create trigger sj_keep_publication before update on public.sj_jobs
    for each row execute function public.sj_keep_publication_date();

