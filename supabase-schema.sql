-- These tables are private. Only server-side service-role credentials may
-- access them; no policies grant browser/anonymous/authenticated access.

create table if not exists public.sj_users (
    user_id bigint primary key,
    chat_id bigint not null,
    settings jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    last_notified_at timestamptz
);

create table if not exists public.sj_jobs (
    id bigint generated by default as identity primary key,
    source text not null,
    url text not null,
    title text not null,
    company text,
    location text,
    description text,
    salary_min numeric,
    salary_currency text,
    remote boolean,
    russian boolean,
    serbian_required boolean,
    published_at timestamptz,
    expires_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (source, url)
);

create table if not exists public.sj_favorites (
    user_id bigint not null references public.sj_users(user_id) on delete cascade,
    job_id bigint not null references public.sj_jobs(id) on delete cascade,
    created_at timestamptz not null default now(),
    primary key (user_id, job_id)
);

create table if not exists public.sj_deliveries (
    user_id bigint not null references public.sj_users(user_id) on delete cascade,
    job_id bigint not null references public.sj_jobs(id) on delete cascade,
    delivered_at timestamptz not null default now(),
    primary key (user_id, job_id)
);

create table if not exists public.sj_source_status (
    source text primary key,
    payload jsonb not null
);

create index if not exists sj_jobs_created_idx on public.sj_jobs (created_at desc, id desc);

alter table public.sj_users enable row level security;
alter table public.sj_jobs enable row level security;
alter table public.sj_favorites enable row level security;
alter table public.sj_deliveries enable row level security;
