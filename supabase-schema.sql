create or replace function public.sj_renew_update(p_update_id bigint,p_owner text,p_seconds integer)
returns boolean language plpgsql set search_path = public as $$
declare claimed bigint;
begin
    if p_seconds < 1 or p_seconds > 1800 then raise exception 'Invalid update renewal'; end if;
    update sj_webhook_events set expires_at=now()+make_interval(secs=>p_seconds)
        where update_id=p_update_id and owner=p_owner and not completed returning update_id into claimed;
    return claimed is not null;
end $$;
revoke all on function public.sj_renew_update(bigint,text,integer) from public,anon,authenticated;
grant execute on function public.sj_renew_update(bigint,text,integer) to service_role;
