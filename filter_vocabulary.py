def keyword_contains(text, term):
    """Match an exact term, or listed inflections of a known single-word role.

    Import locally because filters imports this vocabulary. In particular,
    phrases, technology names and exclusions retain their exact-term behavior.
    """
    from filters import contains, normalize

    forms = KEYWORD_FORMS.get(normalize(term))
    if forms is None:
        return contains(text, term)
    pattern = r'(?<!\w)(?:' + '|'.join(re.escape(form) for form in forms) + r')(?!\w)'
    return bool(re.search(pattern, normalize(text)))
