"""Tree-shake the locked pako codec into a dependency-free Serverless module."""
import json
import os
from pathlib import Path
import subprocess
ROOT=Path(__file__).resolve().parents[1]
out=ROOT/'serverless/tgcloud/lib/image-codec.js'
version=json.loads((ROOT/'serverless/package.json').read_text())['devDependencies']['pako']
subprocess.run(['npm','exec','--yes','--ignore-scripts','--package=esbuild@0.25.12','--','esbuild',
                'tools/image-codec-entry.mjs','--bundle','--minify','--format=esm','--platform=neutral',
                '--target=es2020','--legal-comments=inline','--outfile='+str(out)],cwd=ROOT,
               env=dict(os.environ,npm_config_cache=str(ROOT/'work/npm-cache')),check=True)
out.write_text('// Bundled pako (MIT/Zlib): tools/licenses/pako.txt. Generated by tools/build_image_codec.py.\n'
               +f"export const CODEC_SOURCE='pako@{version}';\n"+out.read_text())
