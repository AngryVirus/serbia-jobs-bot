"""Build the bundled bitmap font atlas and optional illustrated header (Pillow, build time only)."""
import argparse
import base64
import json
from pathlib import Path
import zlib
from PIL import Image, ImageDraw, ImageFont
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'serverless/tgcloud/lib/image-fonts.js'
HEADER_OUT=OUT.with_name('image-header.js')
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--banner',type=Path)
args=parser.parse_args()
chars=sorted(set([*range(32,127),*range(160,383),*range(0x400,0x460),*map(ord,'—–…✓•№«»→←↩≠≥≤□Ёё’‘“”')]))
raw=bytearray();fonts={}
for name,path,size in [('body','DejaVuSans.ttf',32),('bold','DejaVuSans-Bold.ttf',34),('title','DejaVuSerif-Bold.ttf',44)]:
 font=ImageFont.truetype('/usr/share/fonts/truetype/dejavu/'+path,size)
 glyphs={}
 for code in chars:
  char=chr(code);left,top,right,bottom=font.getbbox(char);w,h=right-left,bottom-top
  img=Image.new('L',(max(1,w),max(1,h)))
  ImageDraw.Draw(img).text((-left,-top),char,font=font,fill=255)
  pixels=img.tobytes() if w and h else b''
  glyphs[str(code)]=[w,h,left,top,round(font.getlength(char)),len(raw)]
  raw.extend(bytes((v//17)*17 for v in pixels))
 fonts[name]={'size':size,'glyphs':glyphs}
if args.banner:
 img=Image.open(args.banner).convert('RGB').resize((960,320),Image.Resampling.LANCZOS)
 # Fade into the exact body colour; rendering is deterministic and entirely local.
 px=img.load()
 for y in range(270,320):
  a=(y-270)/49
  for x in range(960):px[x,y]=tuple(round(c*(1-a)+d*a) for c,d in zip(px[x,y],(251,246,236)))
 adaptive=img.quantize(colors=61,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE)
 palette=Image.new('P',(1,1));palette.putpalette(adaptive.getpalette()[:183]+[190,45,60,35,83,142,250,247,240]+[251,246,236]*192)
 indexed=img.quantize(palette=palette,dither=Image.Dither.NONE)
 header={'width':960,'height':320,'palette':indexed.getpalette(),'indexed':base64.b64encode(zlib.compress(indexed.tobytes(),9)).decode()}
else:
 header=json.loads(next(x for x in HEADER_OUT.read_text().splitlines() if x.startswith('export const HEADER=')).removeprefix('export const HEADER=').split(';')[0])
content='// Generated by tools/build_menu_assets.py; DejaVu font licence: tools/licenses/dejavu-fonts.txt.\n'
HEADER_OUT.write_text('// Generated illustration data; no credentials.\nexport const HEADER='+json.dumps(header,separators=(',',':'))+'; // pragma: allowlist secret\n')
content+='export const FONTS='+json.dumps(fonts,separators=(',',':'))+';\n'
content+='export const FONT_DATA='+json.dumps(base64.b64encode(zlib.compress(bytes(raw),9)).decode())+'; // pragma: allowlist secret\n'
OUT.write_text(content)
print('Built bundled header and',len(chars),'glyphs per font;',OUT.stat().st_size,'bytes')
