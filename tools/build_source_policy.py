"""Keep the cloud search policy identical to the Python collector policy."""
import json
import re
from pathlib import Path
import sys

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root))
from source_policy import ACTIVE_TELEGRAM, DISABLED_SITES
from sources import SOURCES
from filter_vocabulary import CITY_ALIASES, KEYWORD_FORMS

text = '// Generated by tools/build_source_policy.py.\n'
text += 'const telegram = new Set(' + json.dumps(sorted(ACTIVE_TELEGRAM)) + ');\n'
text += 'const disabledSites = new Set(' + json.dumps(sorted(DISABLED_SITES)) + ');\n'
text += "export const sourceEnabled = id => /^(tg_|telegram_)/.test(id || '') ? telegram.has(id) : !disabledSites.has(id);\n"
(root / 'serverless/tgcloud/lib/source-policy.js').write_text(text)

config = root / 'serverless/tgcloud/lib/config.js'
text = config.read_text()
names = json.dumps({key: source.name for key, source in SOURCES.items()}, ensure_ascii=False)
text, changed = re.subn(r'^export const SOURCE_NAMES = .*?;$',
                       lambda _: 'export const SOURCE_NAMES = ' + names + ';', text, flags=re.M)
if changed != 1:
    raise RuntimeError('Expected exactly one cloud source registry')
config.write_text(text)

text = config.read_text()
for export, value in [('CITIES', CITY_ALIASES), ('KEYWORD_FORMS', KEYWORD_FORMS)]:
    line = 'export const ' + export + ' = ' + json.dumps(value, ensure_ascii=False) + ';'
    pattern = r'^export const ' + export + r' = .*?;$'
    if re.search(pattern, text, re.M):
        text = re.sub(pattern, lambda _: line, text, flags=re.M)
    else:
        text = text.rstrip() + '\n' + line + '\n'
config.write_text(text)
